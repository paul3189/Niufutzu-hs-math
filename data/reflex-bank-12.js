  /* 多項式（降冪係數陣列）轉 LaTeX；係數 ±1 不寫 1、係數 0 整項不寫 */
  function polyTex(cs) {
    var s = "", n = cs.length - 1;
    for (var i = 0; i <= n; i++) {
      var c = cs[i], p = n - i;
      if (c === 0) continue;
      var a = Math.abs(c);
      var body = (p === 0) ? String(a) : ((a === 1 ? "" : String(a)) + "x" + (p > 1 ? "^" + p : ""));
      if (s === "") s = (c < 0 ? "-" : "") + body;
      else s += (c < 0 ? "-" : "+") + body;
    }
    return s || "0";
  }

