  function lin(cs, vs) {
    var s = "";
    for (var i = 0; i < cs.length; i++) {
      var c = cs[i];
      if (c === 0) continue;
      var a = Math.abs(c);
      s += (c < 0 ? "-" : (s ? "+" : "")) + (a === 1 && vs[i] ? "" : a) + vs[i];
    }
    return s || "0";
  }
