  /* aX+b 形式（a≠0） */
  function lin(a, b, v) {
    var s = (a === 1 ? "" : a === -1 ? "-" : String(a)) + v;
    if (b > 0) s += "+" + b; else if (b < 0) s += String(b);
    return s;
  }
  /* (x-h)、(x+3)、或 x */
  function sh(v, h) {
    if (h === 0) return v;
    return "(" + v + (h > 0 ? "-" + h : "+" + (-h)) + ")";
  }
  /* 複數 p+qi 的寫法（q≠0） */
  function cpx(p, q) {
    var im = (q === 1 ? "" : q === -1 ? "-" : String(q)) + "i";
    if (p === 0) return im;
    return p + (q > 0 ? "+" : "") + im;
  }
  /* 多項式 c[0]x^n+…+c[n]（係數為整數，首項非 0） */
  function poly(c) {
    var n = c.length - 1, s = "";
    for (var i = 0; i <= n; i++) {
      var k = c[i], e = n - i;
      if (k === 0) continue;
      var xs = e === 0 ? "" : e === 1 ? "x" : "x^" + e;
      var abs = Math.abs(k), body = (abs === 1 && e > 0 ? "" : String(abs)) + xs;
      s += (k < 0 ? "-" : (s ? "+" : "")) + body;
    }
    return s || "0";
  }
  function gcd(x, y) { x = Math.abs(x); y = Math.abs(y); while (y) { var t = x % y; x = y; y = t; } return x; }
  /* 化簡根號：28 寫成 2√7 */
  function root(d) {
    var o = 1, r = d;
    for (var f = 2; f * f <= r; f++) while (r % (f * f) === 0) { r /= f * f; o *= f; }
    return r === 1 ? String(o) : (o === 1 ? "" : o) + "\\sqrt{" + r + "}";
  }
  function pt(v, onY) { return onY ? "$(0,\\pm" + v + ")$" : "$(\\pm" + v + ",0)$"; }
  function nz(lo, hi) { var v; do { v = lo + ri(hi - lo + 1); } while (v === 0); return v; }

